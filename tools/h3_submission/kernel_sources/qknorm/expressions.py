def apply_qknorm_4_0(oq,ok,q,k,gq,gk,eq,ek):
    qf=ntl.cast(ntl.reshape(q,(4,128)),ntl.float32)
    qss=qf*qf
    ql,qr=ntl.split(ntl.reshape(qss,(4,64,2)))
    qss=ql+qr
    ql,qr=ntl.split(ntl.reshape(qss,(4,32,2)))
    qss=ql+qr
    ql,qr=ntl.split(ntl.reshape(qss,(4,16,2)))
    qss=ql+qr
    ql,qr=ntl.split(ntl.reshape(qss,(4,8,2)))
    qss=ql+qr
    ql,qr=ntl.split(ntl.reshape(qss,(4,4,2)))
    qss=ql+qr
    ql,qr=ntl.split(ntl.reshape(qss,(4,2,2)))
    qss=ql+qr
    ql,qr=ntl.split(ntl.reshape(qss,(4,1,2)))
    qss=ql+qr
    qinv=ntl.expand_dims(ntl.rsqrt(ntl.reshape(qss,(4,))*0.0078125+ntl.cast(eq,ntl.float32)),1)
    qweighted=qf*ntl.cast(ntl.reshape(gq,(4,128)),ntl.float32)
    qrounded=qweighted*qinv
    qres=ntl.fma(qweighted,qinv,-qrounded)
    qbits=ntl.cast(qrounded,ntl.int32,bitcast=True)
    qabs=qbits&2147483647
    qexp=(qabs>>23)&255
    qdiscard=ntl.maximum(13,ntl.minimum(24,126-qexp))
    qsig=(qabs&8388607)|8388608
    qmid=(qsig&((1<<qdiscard)-1))==(1<<(qdiscard-1))
    qdirection=ntl.where((qbits<0)==(qres<0),1,-1)
    qcorrect=ntl.cast(qbits+qdirection,ntl.float32,bitcast=True)
    qrounded=ntl.where(qmid&(qres!=0)&(qexp>=102)&(qexp<=142),qcorrect,qrounded)
    oq=ntl.reshape(qrounded,(1,4,128))
    kf=ntl.cast(ntl.reshape(k,(4,128)),ntl.float32)
    kss=kf*kf
    kl,kr=ntl.split(ntl.reshape(kss,(4,64,2)))
