    kss=kl+kr
    kl,kr=ntl.split(ntl.reshape(kss,(4,16,2)))
    kss=kl+kr
    kl,kr=ntl.split(ntl.reshape(kss,(4,8,2)))
    kss=kl+kr
    kl,kr=ntl.split(ntl.reshape(kss,(4,4,2)))
    kss=kl+kr
    kl,kr=ntl.split(ntl.reshape(kss,(4,2,2)))
    kss=kl+kr
    kl,kr=ntl.split(ntl.reshape(kss,(4,1,2)))
    kss=kl+kr
    kinv=ntl.expand_dims(ntl.rsqrt(ntl.reshape(kss,(4,))*0.0078125+ntl.cast(ek,ntl.float32)),1)
    kweighted=kf*ntl.cast(ntl.reshape(gk,(4,128)),ntl.float32)
