    krdirection=ntl.where((krbits<0)==(kerr<0),1,-1)
    krcorrect=ntl.cast(krbits+krdirection,ntl.float32,bitcast=True)
    kr=ntl.where(krmid&(kerr!=0)&(krexp>=102)&(krexp<=142),krcorrect,kr)
    oq=ntl.reshape(ntl.where(ntl.expand_dims(col,0)<rotary,qr,qnorm),(1,8,128))
    ok=ntl.reshape(ntl.where(ntl.expand_dims(col,0)<rotary,kr,knorm),(1,8,128))

