import ninetoothed.language as ntl
def arrange_8(oq,ok,q,k,gq,gk,cache,pos,eq,ek,rd):
    oq=oq.tile((1,8,128))
    ok=ok.tile((1,8,128))
    q=q.tile((1,8,128))
    k=k.tile((1,8,128))
    gq=gq.tile((1,8,128))
    gk=gk.tile((1,8,128))
    cache=cache.flatten().tile((1,)).unsqueeze(1).unsqueeze(2).expand(oq.shape)
    pos=pos.flatten().tile((1,)).unsqueeze(1).unsqueeze(2).expand(oq.shape)
    return oq,ok,q,k,gq,gk,cache,pos,eq,ek,rd

def apply_8_0(oq,ok,q,k,gq,gk,cache,pos,eq,ek,rd):
    qf=ntl.cast(ntl.reshape(q,(8,128)),ntl.float32)
    qss=qf*qf
    ql,qr=ntl.split(ntl.reshape(qss,(8,64,2)))
    qss=ql+qr
    ql,qr=ntl.split(ntl.reshape(qss,(8,32,2)))
    qss=ql+qr
    ql,qr=ntl.split(ntl.reshape(qss,(8,16,2)))
    qss=ql+qr
    ql,qr=ntl.split(ntl.reshape(qss,(8,8,2)))
    qss=ql+qr
    ql,qr=ntl.split(ntl.reshape(qss,(8,4,2)))
    qss=ql+qr
    ql,qr=ntl.split(ntl.reshape(qss,(8,2,2)))
    qss=ql+qr
    ql,qr=ntl.split(ntl.reshape(qss,(8,1,2)))
    qss=ql+qr
    qinv=ntl.expand_dims(ntl.rsqrt(ntl.reshape(qss,(8,))*0.0078125+ntl.cast(eq,ntl.float32)),1)
    qweighted=qf*ntl.cast(ntl.reshape(gq,(8,128)),ntl.float32)
    qrounded=qweighted*qinv
    qres=ntl.fma(qweighted,qinv,-qrounded)
    qbits=ntl.cast(qrounded,ntl.int32,bitcast=True)
    qabs=qbits&2147483647
    qexp=(qabs>>23)&255
    qdiscard=ntl.maximum(13,ntl.minimum(24,126-qexp))
    qsig=(qabs&8388607)|8388608
    qmid=(qsig&((1<<qdiscard)-1))==(1<<(qdiscard-1))
    qdirection=ntl.where((qbits<0)==(qres<0),1,-1)
    qcorrect=ntl.cast(qbits+qdirection,ntl.float32,bitcast=True)
    qrounded=ntl.where(qmid&(qres!=0)&(qexp>=102)&(qexp<=142),qcorrect,qrounded)
    qnorm=ntl.cast(ntl.cast(qrounded,ntl.float16),ntl.float32)
    kf=ntl.cast(ntl.reshape(k,(8,128)),ntl.float32)
    kss=kf*kf
    kl,kr=ntl.split(ntl.reshape(kss,(8,64,2)))
    kss=kl+kr
    kl,kr=ntl.split(ntl.reshape(kss,(8,32,2)))
    kss=kl+kr
    kl,kr=ntl.split(ntl.reshape(kss,(8,16,2)))
    kss=kl+kr
    kl,kr=ntl.split(ntl.reshape(kss,(8,8,2)))
    kss=kl+kr
    kl,kr=ntl.split(ntl.reshape(kss,(8,4,2)))
    kss=kl+kr
    kl,kr=ntl.split(ntl.reshape(kss,(8,2,2)))
    kss=kl+kr
    kl,kr=ntl.split(ntl.reshape(kss,(8,1,2)))
    kss=kl+kr
    kinv=ntl.expand_dims(ntl.rsqrt(ntl.reshape(kss,(8,))*0.0078125+ntl.cast(ek,ntl.float32)),1)
    kweighted=kf*ntl.cast(ntl.reshape(gk,(8,128)),ntl.float32)
    krounded=kweighted*kinv
    kres=ntl.fma(kweighted,kinv,-krounded)
    kbits=ntl.cast(krounded,ntl.int32,bitcast=True)
    kabs=kbits&2147483647
    kexp=(kabs>>23)&255
    kdiscard=ntl.maximum(13,ntl.minimum(24,126-kexp))
    ksig=(kabs&8388607)|8388608
    kmid=(ksig&((1<<kdiscard)-1))==(1<<(kdiscard-1))
    kdirection=ntl.where((kbits<0)==(kres<0),1,-1)
    kcorrect=ntl.cast(kbits+kdirection,ntl.float32,bitcast=True)
    krounded=ntl.where(kmid&(kres!=0)&(kexp>=102)&(kexp<=142),kcorrect,krounded)
    knorm=ntl.cast(ntl.cast(krounded,ntl.float16),ntl.float32)
    rotary=ntl.cast(rd,ntl.int32)
    half=rotary//2
    col=ntl.arange(0,128)
    partner=ntl.where(col<rotary,ntl.where(col<half,col+half,col-half),col)
    gather_index=ntl.broadcast_to(ntl.expand_dims(partner,0),(8,128))
    qp=ntl.gather(qnorm,gather_index,1)
    kp=ntl.gather(knorm,gather_index,1)
    token=ntl.reshape(oq.offsets(0),(1,1))
    freq=ntl.expand_dims(ntl.where(col<half,col,col-half),0)
    section=half//3
    axis=ntl.where(freq<section,0,ntl.where(freq<2*section,1,2))
    valid=(token<q.source.shape[0])&(ntl.expand_dims(col,0)<rotary)
    position=ntl.load(pos.source.data_ptr()+axis*pos.source.stride(0)+token*pos.source.stride(1),mask=valid,other=0)
    position=ntl.where((position>=0)&(position<cache.source.shape[0]),position,0)
    offset=position*cache.source.stride(0)+freq
    cs=ntl.cast(ntl.load(cache.source.data_ptr()+offset,mask=valid,other=1),ntl.float32)
    sn=ntl.cast(ntl.load(cache.source.data_ptr()+offset+half,mask=valid,other=0),ntl.float32)
    signed_sn=ntl.where(ntl.expand_dims(col,0)<half,-sn,sn)
    qa=qnorm*cs
    qb=qp*signed_sn
    qr=qa+qb
    qv=qr-qa
    qerr=(qa-(qr-qv))+(qb-qv)
    qrbits=ntl.cast(qr,ntl.int32,bitcast=True)
    qrabs=qrbits&2147483647
    qrexp=(qrabs>>23)&255
    qrdiscard=ntl.maximum(13,ntl.minimum(24,126-qrexp))
    qrsig=(qrabs&8388607)|8388608
    qrmid=(qrsig&((1<<qrdiscard)-1))==(1<<(qrdiscard-1))
    qrdirection=ntl.where((qrbits<0)==(qerr<0),1,-1)
    qrcorrect=ntl.cast(qrbits+qrdirection,ntl.float32,bitcast=True)
    qr=ntl.where(qrmid&(qerr!=0)&(qrexp>=102)&(qrexp<=142),qrcorrect,qr)
    ka=knorm*cs
    kb=kp*signed_sn
    kr=ka+kb
    kv=kr-ka
    kerr=(ka-(kr-kv))+(kb-kv)
    krbits=ntl.cast(kr,ntl.int32,bitcast=True)
    krabs=krbits&2147483647
    krexp=(krabs>>23)&255
    krdiscard=ntl.maximum(13,ntl.minimum(24,126-krexp))
    krsig=(krabs&8388607)|8388608
